//! BD-09 (百度) → WGS-84 坐标转换。
//!
//! 一比一翻译自 Python `run.py::bd09Towgs84`；用真实 Python 输出作 golden value
//! 校准到 1e-9 精度。这部分纯算法、无外部依赖。

use std::f64::consts::PI;

const X_PI: f64 = PI * 3000.0 / 180.0;
const A: f64 = 6_378_245.0;
const EE: f64 = 0.006_693_421_622_965_943;

/// 把百度 BD-09 坐标（先 lng 后 lat）转成 WGS-84（先 lng 后 lat）。
pub fn bd09_to_wgs84(lng: f64, lat: f64) -> (f64, f64) {
    let x = lng - 0.0065;
    let y = lat - 0.006;
    let z = (x * x + y * y).sqrt() - 0.00002 * (y * X_PI).sin();
    let theta = y.atan2(x) - 0.000_003 * (x * X_PI).cos();
    let gcj_lng = z * theta.cos();
    let gcj_lat = z * theta.sin();

    // Python: wgs = gcj*2 - gcj - d = gcj - d
    let (d_lat_raw, d_lng_raw) = transform(gcj_lng - 105.0, gcj_lat - 35.0);
    let rad_lat = gcj_lat / 180.0 * PI;
    let magic_sin = rad_lat.sin();
    let magic = 1.0 - EE * magic_sin * magic_sin;
    let sqrt_magic = magic.sqrt();

    let d_lng = (d_lng_raw * 180.0) / (A / sqrt_magic * rad_lat.cos() * PI);
    let d_lat = (d_lat_raw * 180.0) / (A * (1.0 - EE) / (magic * sqrt_magic) * PI);

    (gcj_lng - d_lng, gcj_lat - d_lat)
}

fn transform(x: f64, y: f64) -> (f64, f64) {
    let lat = transform_lat(x, y);
    let lng = transform_lon(x, y);
    (lat, lng)
}

fn transform_lat(x: f64, y: f64) -> f64 {
    let mut ret = -100.0 + 2.0 * x + 3.0 * y + 0.2 * y * y + 0.1 * x * y + 0.2 * x.abs().sqrt();
    ret += (20.0 * (6.0 * x * PI).sin() + 20.0 * (2.0 * x * PI).sin()) * 2.0 / 3.0;
    ret += (20.0 * (y * PI).sin() + 40.0 * (y / 3.0 * PI).sin()) * 2.0 / 3.0;
    ret += (160.0 * (y / 12.0 * PI).sin() + 320.0 * (y * PI / 30.0).sin()) * 2.0 / 3.0;
    ret
}

fn transform_lon(x: f64, y: f64) -> f64 {
    let mut ret = 300.0 + x + 2.0 * y + 0.1 * x * x + 0.1 * x * y + 0.1 * x.abs().sqrt();
    ret += (20.0 * (6.0 * x * PI).sin() + 20.0 * (2.0 * x * PI).sin()) * 2.0 / 3.0;
    ret += (20.0 * (x * PI).sin() + 40.0 * (x / 3.0 * PI).sin()) * 2.0 / 3.0;
    ret += (150.0 * (x / 12.0 * PI).sin() + 300.0 * (x / 30.0 * PI).sin()) * 2.0 / 3.0;
    ret
}

/// 大圆距离（Haversine），返回米。等价于 Python `geopy.distance.geodesic`
/// 在小距离上的足够近似。我们只需要"两点之间多少米"，不追求 geopy 那种
/// Vincenty/Karney 级别的精度（单步只有几米）。
pub fn haversine_meters(lat1: f64, lng1: f64, lat2: f64, lng2: f64) -> f64 {
    const R: f64 = 6_371_008.8; // mean earth radius in meters
    let phi1 = lat1.to_radians();
    let phi2 = lat2.to_radians();
    let dphi = (lat2 - lat1).to_radians();
    let dlam = (lng2 - lng1).to_radians();
    let a = (dphi / 2.0).sin().powi(2) + phi1.cos() * phi2.cos() * (dlam / 2.0).sin().powi(2);
    let c = 2.0 * a.sqrt().atan2((1.0 - a).sqrt());
    R * c
}

#[cfg(test)]
#[allow(clippy::excessive_precision)] // golden values copied verbatim from Python output
mod tests {
    use super::*;

    fn approx(a: f64, b: f64, tol: f64) -> bool {
        (a - b).abs() < tol
    }

    /// Golden values generated by running the original Python `bd09Towgs84`
    /// (with the 5.0.4 dependencies). Tolerance 1e-9 matches Python's
    /// effective double precision.
    #[test]
    fn matches_python_for_beijing() {
        let (lng, lat) = bd09_to_wgs84(116.40, 39.90);
        assert!(approx(lng, 116.387_366_482_093_981, 1e-9), "lng={lng}");
        assert!(approx(lat, 39.892_267_192_340_015, 1e-9), "lat={lat}");
    }

    #[test]
    fn matches_python_for_shanghai() {
        let (lng, lat) = bd09_to_wgs84(121.47, 31.23);
        assert!(approx(lng, 121.458_958_625_567_121, 1e-9));
        assert!(approx(lat, 31.225_792_394_674_041, 1e-9));
    }

    #[test]
    fn matches_python_for_guangzhou() {
        let (lng, lat) = bd09_to_wgs84(113.27, 23.13);
        assert!(approx(lng, 113.258_235_000_155_494, 1e-9));
        assert!(approx(lat, 23.126_462_379_699_912, 1e-9));
    }

    #[test]
    fn matches_python_for_xian() {
        let (lng, lat) = bd09_to_wgs84(108.94, 34.34);
        assert!(approx(lng, 108.928_866_695_859_341, 1e-9));
        assert!(approx(lat, 34.335_505_393_557_547, 1e-9));
    }

    #[test]
    fn matches_python_for_origin() {
        let (lng, lat) = bd09_to_wgs84(0.0, 0.0);
        assert!(approx(lng, -0.021_990_506_500_769, 1e-9));
        assert!(approx(lat, -0.008_718_241_826_793, 1e-9));
    }

    #[test]
    fn matches_python_for_san_francisco() {
        let (lng, lat) = bd09_to_wgs84(-122.42, 37.77);
        assert!(approx(lng, -122.487_516_393_686_562, 1e-9));
        assert!(approx(lat, 37.768_369_033_290_320, 1e-9));
    }

    #[test]
    fn haversine_zero_distance() {
        assert!(approx(
            haversine_meters(39.0, 116.0, 39.0, 116.0),
            0.0,
            1e-9
        ));
    }

    #[test]
    fn haversine_approx_one_km() {
        // 1 degree of latitude ≈ 111 km
        let d = haversine_meters(39.0, 116.0, 39.009, 116.0);
        assert!(approx(d, 1000.0, 5.0), "expected ~1km, got {d}");
    }
}
